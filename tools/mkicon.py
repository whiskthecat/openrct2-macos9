#!/usr/bin/env python3
"""Generate the Classic Finder icon family from OpenRCT2's own logo pixel art.

Uses upstream's hand-drawn 16, 32 and 48 pixel PNGs (resources/logo) unscaled.
Emits 1-bit icons and masks, 8-bit icons in the Mac system palette, and the
32-bit icons with 8-bit masks that Mac OS 8.5+ shows on thousands/millions of
colours. No game assets are read.
"""
import argparse
from pathlib import Path
import struct
from PIL import Image

LOGO = Path(__file__).resolve().parents[1] / 'upstream/resources/logo'

# Mac 8-bit system CLUT: the descending 6x6x6 cube (indices 0..214), then ten-step
# red, green, blue and grey ramps (215..254) and black (255).
_RAMP = (238, 221, 187, 170, 136, 119, 85, 68, 34, 17)
MAC_CLUT = ([(r, g, b) for r in range(255, -1, -51) for g in range(255, -1, -51) for b in range(255, -1, -51)][:215]
            + [(v, 0, 0) for v in _RAMP] + [(0, v, 0) for v in _RAMP] + [(0, 0, v) for v in _RAMP]
            + [(v, v, v) for v in _RAMP] + [(0, 0, 0)])
assert len(MAC_CLUT) == 256


def load(size):
    image = Image.open(LOGO / f'icon_x{size}.png').convert('RGBA')
    assert image.size == (size, size)
    return image


def bits(image):
    return bytes(sum((1 << (7 - bit)) for bit in range(8) if image.getpixel((x + bit, y)))
                 for y in range(image.height) for x in range(0, image.width, 8))


def mono_and_mask(image):
    mask = image.getchannel('A').point(lambda n: 255 if n >= 128 else 0)
    dark = Image.composite(image.convert('L').point(lambda n: 255 if n < 128 else 0), Image.new('L', image.size), mask)
    return bits(dark) + bits(mask)


def indexed(image):
    out = bytearray()
    for r, g, b, a in image.getdata():
        if a < 128:
            out.append(0)  # masked out; white keeps edges clean if a mask is ignored
            continue
        out.append(min(range(256), key=lambda i: (MAC_CLUT[i][0] - r) ** 2 + (MAC_CLUT[i][1] - g) ** 2
                       + (MAC_CLUT[i][2] - b) ** 2))
    return bytes(out)


def pack_channel(data):
    """icns channel RLE: 0x80+(n-3) repeats a byte n=3..130 times; n-1 then n literal bytes (n<=128)."""
    out, i = bytearray(), 0
    while i < len(data):
        run = 1
        while i + run < len(data) and run < 130 and data[i + run] == data[i]:
            run += 1
        if run >= 3:
            out += bytes((0x80 + run - 3, data[i]))
            i += run
            continue
        start = i
        while i < len(data) and i - start < 128:
            if i + 2 < len(data) and data[i] == data[i + 1] == data[i + 2]:
                break
            i += 1
        out.append(i - start - 1)
        out += data[start:i]
    return bytes(out)


def rgb32(image):
    return b''.join(pack_channel(bytes(image.getchannel(c).getdata())) for c in 'RGB')


def alpha8(image):
    return bytes(image.getchannel('A').getdata())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path(__file__).with_name('RCTIcon.r'))
    parser.add_argument('--preview', type=Path, help='write the 8-bit icons as they map to the Mac palette')
    args = parser.parse_args()
    small, large, huge = load(16), load(32), load(48)
    # BNDL array lengths are stored minus one, as are each local-ID array length.
    bundle = b'ORCG' + struct.pack('>hh', 0, 1)
    bundle += b'ICN#' + struct.pack('>hhh', 0, 0, 128)
    bundle += b'FREF' + struct.pack('>hhh', 0, 0, 128)
    resources = {
        'ICN#': mono_and_mask(large), 'ics#': mono_and_mask(small), 'ich#': mono_and_mask(huge),
        'icl8': indexed(large), 'ics8': indexed(small), 'ich8': indexed(huge),
        'il32': rgb32(large), 'l8mk': alpha8(large),
        'is32': rgb32(small), 's8mk': alpha8(small),
        'ih32': rgb32(huge), 'h8mk': alpha8(huge),
        'BNDL': bundle, 'FREF': b'APPL' + struct.pack('>h', 0) + b'\0',
    }
    lines = ["/* Generated by tools/mkicon.py from OpenRCT2's resources/logo pixel art (unscaled). */"]
    for kind, data in resources.items():
        lines.append(f"data '{kind}' (128, purgeable) {{")
        lines.extend('\t$"' + data[i:i + 16].hex().upper() + '"' for i in range(0, len(data), 16))
        lines.append('};\n')
    args.output.write_text('\n'.join(lines) + '\n')
    if args.preview:
        sheet = Image.new('RGB', (16 + 32 + 48 + 40, 48), (255, 255, 255))
        x = 0
        for image, data in ((small, resources['ics8']), (large, resources['icl8']), (huge, resources['ich8'])):
            mapped = Image.new('RGB', image.size)
            mapped.putdata([MAC_CLUT[i] if a >= 128 else (255, 255, 255)
                            for i, (_, _, _, a) in zip(data, image.getdata())])
            sheet.paste(mapped, (x, 0))
            x += image.width + 20
        sheet.resize((sheet.width * 4, sheet.height * 4), Image.Resampling.NEAREST).save(args.preview)


if __name__ == '__main__':
    main()
