// Shared by the engine's version text and the native 'vers' resource.
#ifndef RCT_CLASSIC_VERSION_H
#define RCT_CLASSIC_VERSION_H
#define RCT_VERSION_MAJOR 0
#define RCT_VERSION_MINOR 6
#define RCT_VERSION_PATCH 0
// 0 for a release; otherwise the development build number (shown as -devN).
#define RCT_VERSION_DEVELOPMENT 0
#define RCT_VERSION_STRING_(n) #n
#define RCT_VERSION_STRING(n) RCT_VERSION_STRING_(n)
#define RCT_VERSION_RELEASE_ RCT_VERSION_STRING(RCT_VERSION_MAJOR) "." RCT_VERSION_STRING(RCT_VERSION_MINOR) "." RCT_VERSION_STRING(RCT_VERSION_PATCH)
#if RCT_VERSION_DEVELOPMENT
#define RCT_PORT_VERSION RCT_VERSION_RELEASE_ "-dev" RCT_VERSION_STRING(RCT_VERSION_DEVELOPMENT)
#else
#define RCT_PORT_VERSION RCT_VERSION_RELEASE_
#endif
#define OPENRCT2_VERSION_TAG "v" RCT_PORT_VERSION
#endif
